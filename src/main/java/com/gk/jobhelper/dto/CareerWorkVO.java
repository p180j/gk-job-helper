package com.gk.jobhelper.dto;

public class CareerWorkVO {
    private String company;
    private String position;
    private String startDate;
    private String endDate;
    private String description;
    private String region;
    private String organizationNature;
    private String industry;
    private String positionType;
    private String organizationLevel;
    private Boolean employed;
    private String evidenceStatus;
    public String getCompany() { return company; }
    public void setCompany(String company) { this.company = company; }
    public String getPosition() { return position; }
    public void setPosition(String position) { this.position = position; }
    public String getStartDate() { return startDate; }
    public void setStartDate(String startDate) { this.startDate = startDate; }
    public String getEndDate() { return endDate; }
    public void setEndDate(String endDate) { this.endDate = endDate; }
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }
    public String getRegion() { return region; }
    public void setRegion(String region) { this.region = region; }
    public String getOrganizationNature() { return organizationNature; }
    public void setOrganizationNature(String organizationNature) { this.organizationNature = organizationNature; }
    public String getIndustry() { return industry; }
    public void setIndustry(String industry) { this.industry = industry; }
    public String getPositionType() { return positionType; }
    public void setPositionType(String positionType) { this.positionType = positionType; }
    public String getOrganizationLevel() { return organizationLevel; }
    public void setOrganizationLevel(String organizationLevel) { this.organizationLevel = organizationLevel; }
    public Boolean getEmployed() { return employed; }
    public void setEmployed(Boolean employed) { this.employed = employed; }
    public String getEvidenceStatus() { return evidenceStatus; }
    public void setEvidenceStatus(String evidenceStatus) { this.evidenceStatus = evidenceStatus; }
}
